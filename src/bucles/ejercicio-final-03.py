# range(5, 51) genera números desde 5 hasta 50.
for multiplicador in range(5, 51):
    # Realizamos la multiplicación: Base (5) * Multiplicador actual
    resultado = 5 * multiplicador

    # Imprimimos el resultado en un formato claro
    print(f"5 x {multiplicador:2} = {resultado}")

