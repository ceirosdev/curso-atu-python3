# Inicializar el contador que representará la posición del término
contador = 1

# El bucle se ejecutará mientras el contador sea menor o igual a 25
while contador <= 25:
    # Calcular el término actual multiplicando el número de posición por 11
    termino = contador * 11

    # Imprimir el término generado
    print(termino)

    # Incrementar el contador para pasar al siguiente término
    contador += 1
