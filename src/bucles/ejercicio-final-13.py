# Empezamos con el primer múltiplo de 8, que es 8.
multiplo = 8

# Bucle while: se ejecuta mientras el múltiplo actual sea menor o igual a 500
while multiplo <= 500:
    # Imprimir el múltiplo actual
    print(multiplo)

    # Incrementar el múltiplo en 8 para obtener el siguiente múltiplo
    multiplo += 8
